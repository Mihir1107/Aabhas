"""
Synthetic burn-in parametric dataset generator for SIH26170.

Produces burn-in electrical measurements at 0/24/96/168 h for N_LOTS x M_PARTS
components, with a hierarchical good-part degradation model, physically
grounded Arrhenius scaling, seven defect/trap archetypes, and explicit
censoring semantics.

--------------------------------------------------------------------------
DESIGN ASSUMPTIONS (stated explicitly; see README for discussion)
--------------------------------------------------------------------------
A1. Cross-parameter correlation is generated by a 2-factor model, not a
    hand-written correlation matrix. Factor 1 is the process/Vth corner
    (fast+leaky vs slow+tight). Factor 2 is a gate-oxide/defect-density
    factor that raises leakage without making the part fast. This
    guarantees a positive-definite correlation matrix and gives every
    correlation a physical name. Resulting corr(iddq, leakage) = +0.91,
    corr(leakage, prop_delay) = -0.75, corr(vth_shift, prop_delay) = +0.73.

A2. `vth_shift_mv` is defined as the measured threshold voltage offset from
    the *design nominal*, not from this part's own 0 h reading. If it were
    defined relative to t=0 it would be identically zero at 0 h for every
    part, which would destroy the cross-sectional joint distribution at the
    first checkpoint. It therefore has a non-degenerate spread at 0 h and a
    positive drift thereafter.

A3. Degradation magnitude is expressed as a fractional drift *per field
    year*, then multiplied by the Arrhenius-equivalent field years of each
    checkpoint. Ea, T_use and T_stress are live inputs: changing them
    changes the dataset. Nothing is hardcoded to AF = 77.7.

A4. Defects are driven by a named *failure mechanism* that selects which
    parameters degrade. A junction-leakage defect moves iddq/leakage/supply
    current; an oxide-trap (NBTI-like) defect moves vth_shift/prop_delay.
    This is more physical than "everything drifts 8x", and it is what makes
    the in-spec constraint satisfiable on tight-margin parameters like
    prop_delay.

A5. Measurement noise sd is 12% of the part-to-part sd (a plausible gauge
    R&R), independent per checkpoint and per parameter.

A6. Beta (the saturating exponent) is fixed per parameter with a small
    per-lot jitter, and lives in [0.5, 1.0] as specified. Physics note: real
    NBTI Vth-shift exponents are nearer 0.15-0.25, so [0.5, 1.0] is a
    deliberately conservative (less strongly saturating) band.

A7. The in-spec constraint is enforced *by construction*: every injected
    offset is scaled down until all measured checkpoints sit inside the
    datasheet limits with a safety margin. Nothing is filtered afterwards.
    The one deliberate exception is the latent 168 h value of a part that
    fails hard and is pulled; that value is out of spec, is never written to
    the measurements file, and is recorded only in ground truth.
"""

