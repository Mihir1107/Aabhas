K_BOLTZMANN_EV_PER_K = 8.617e-5   # eV/K
HOURS_PER_YEAR = 8766.0           # 365.25 * 24


def arrhenius_af(ea_ev: float, t_use_c: float, t_stress_c: float) -> float:
    """Arrhenius acceleration factor between a stress and a use temperature.

        AF = exp[ (Ea / k) * (1/T_use - 1/T_stress) ]

    Temperatures are given in Celsius and converted to Kelvin internally.
    Ea in eV, k = 8.617e-5 eV/K.

    Reference check (Part 1.2 of the research doc): Ea=0.7 eV, T_use=55 C,
    T_stress=125 C gives AF = 77.7. That number is *derived here*, never
    hardcoded, so changing Ea or either temperature re-scales the dataset.
    """
    t_use_k = t_use_c + 273.15
    t_stress_k = t_stress_c + 273.15
    return math.exp((ea_ev / K_BOLTZMANN_EV_PER_K) * (1.0 / t_use_k - 1.0 / t_stress_k))


def field_years_equivalent(hours: float, af: float) -> float:
    """Field-use years represented by `hours` of stress at acceleration `af`."""
    return hours * af / HOURS_PER_YEAR


