@dataclass
class ParamSpec:
    name: str
    unit: str
    v0_mean: float              # population mean of the 0 h value
    v0_sd_part: float           # component-level random effect sd on v0
    v0_sd_lot: float            # lot-level random effect sd on v0
    limit_lo: float             # datasheet lower limit
    limit_hi: float             # datasheet upper limit
    direction: str              # "higher_is_worse" | "two_sided"
    drift_frac_per_field_year: float   # fractional drift per field year
    drift_ref: float            # magnitude the fraction is applied to
    beta: float                 # saturating exponent, 0.5 <= beta <= 1.0
    f1: float                   # loading on factor 1 (process / Vth corner)
    f2: float                   # loading on factor 2 (oxide / defect density)
    phys_floor: float | None = None   # tester measurement floor; strictly
                                      # positive quantities cannot read below it
    log_scale: bool = False           # if True the parameter is LOG-NORMAL:
                                      # v0_mean is read as the median, and
                                      # v0_sd_part / v0_sd_lot as log-scale sds

    @property
    def drift_168_target(self) -> float:
        """Placeholder; the real value is computed by the generator because it
        depends on the Arrhenius settings. Kept as a property for clarity."""
        raise NotImplementedError


def default_params() -> list[ParamSpec]:
    """Five parameters for a mixed digital/analog part.

    Iddq and input leakage are LOG-NORMAL. Real quiescent-current distributions
    are strongly right-skewed -- a lot's worst parts sit several times the lot
    median, not a few percent above it -- and modelling them as Gaussian would
    quietly disarm the robust-statistics argument, because on symmetric data
    mean/sd and median/MAD agree and the breakdown-point distinction stops
    mattering. It also makes the problem statement's own worked example
    (lot averaging ~10 uA, one part at 45 uA, datasheet max 50 uA)
    expressible: that part is a log-normal tail, not a 16-sigma Gaussian event.


    Values are plausible for a screened space-grade CMOS device. The key
    design ratio is drift_at_168h / v0_sd_part ~= 0.70 for every parameter:
    that is what makes a 5-10x drifter land in the 3.5-7 robust-sigma range
    at 168 h, so AEC-Q001 DPAT at 6 sigma catches *some* Type I parts and
    misses others. If drift were tiny relative to part-to-part spread, DPAT
    would catch nothing and the ablation story would be flat; if it were
    huge, DPAT would catch everything and the dataset would be trivial.
    """
    return [
        ParamSpec("iddq_ua", "uA", 12.0, 0.215, 0.170, 0.0, 50.0,
                  "higher_is_worse", 0.0785, 12.0, 0.62, 0.92, 0.30, log_scale=True),
        ParamSpec("leakage_na", "nA", 25.0, 0.235, 0.185, 0.0, 100.0,
                  "higher_is_worse", 0.0940, 25.0, 0.58, 0.94, 0.24, log_scale=True),
        ParamSpec("prop_delay_ns", "ns", 8.00, 0.300, 0.220, 6.0, 10.0,
                  "higher_is_worse", 0.01760, 8.00, 0.70, -0.86, 0.10),
        ParamSpec("supply_current_ma", "mA", 45.0, 3.00, 2.40, 30.0, 65.0,
                  "higher_is_worse", 0.03135, 45.0, 0.66, 0.62, 0.30, phys_floor=1.0),
        ParamSpec("vth_shift_mv", "mV", 0.0, 4.00, 3.00, -50.0, 50.0,
                  "two_sided", 0.4700, 4.00, 0.55, -0.88, 0.12),
    ]


