def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("--seed", type=int, default=GeneratorConfig.seed)
    ap.add_argument("--out", type=Path, default=Path("data"))
    ap.add_argument("--lots", type=int, default=GeneratorConfig.n_lots)
    ap.add_argument("--parts-per-lot", type=int, default=GeneratorConfig.parts_per_lot)
    ap.add_argument("--types", type=str, default="I,II,III,IV,V,VI,VII",
                    help="comma separated defect types to enable (staging aid)")
    ap.add_argument("--type3-band", type=float,
                    default=GeneratorConfig.type3_band_pct,
                    help="percentile half-band Type III must stay inside")
    ap.add_argument("--leakage-corr", type=float,
                    default=GeneratorConfig.leakage_corr_target,
                    help="target corr(iddq, leakage); rescales the factor model")
    ap.add_argument("--no-censoring", action="store_true")
    args = ap.parse_args()

    cfg = GeneratorConfig(
        seed=args.seed,
        n_lots=args.lots,
        parts_per_lot=args.parts_per_lot,
        enabled_types=tuple(t.strip() for t in args.types.split(",") if t.strip()),
        enable_censoring=not args.no_censoring,
        leakage_corr_target=args.leakage_corr,
        type3_band_pct=args.type3_band,
    )
    if cfg.parts_per_lot < 30:
        raise SystemExit("AEC-Q001 requires at least 30 parts per lot for limit estimation")

    gen = BurnInGenerator(cfg)
    meas, gt = gen.generate()

    out = args.out
    out.mkdir(parents=True, exist_ok=True)
    # Tester reporting resolution. Real ATE reports a handful of significant
    # digits, not float64, and rounding here also keeps the CSV a sane size.
    meas = meas.round({n: 4 for n in gen.pnames})
    meas.to_csv(out / "burnin_measurements.csv", index=False)
    meas.to_csv(out / "burnin_measurements.csv.gz", index=False,
                compression="gzip")
    gt.to_csv(out / "ground_truth.csv", index=False)

    meta = {
        "config": cfg.to_dict(),
        "parameters": [dataclasses.asdict(p) for p in gen.params],
        "failure_mechanisms": FAILURE_MECHANISMS,
        "defect_type_glossary": DEFECT_TYPES,
        "derived": {
            "acceleration_factor": gen.af,
            "field_years_by_checkpoint": {str(k): v for k, v in gen.field_years.items()},
            "median_drift_at_final_checkpoint": dict(zip(gen.pnames, gen.drift_end.tolist())),
            "lambda0": dict(zip(gen.pnames, gen.lambda0.tolist())),
            "factor1_scale": gen.factor1_scale,
            "correlation_matrix": gen.R.tolist(),
            "correlation_labels": gen.pnames,
            "type6_lots": gen.diag["type6_lots"],
            "type7_boards": gen.diag["type7_boards"],
            "type3_report": gen.diag["type3"],
        },
    }
    plain = json.loads(json.dumps(meta, default=_jsonable))
    (out / "config.json").write_text(json.dumps(plain, indent=2))
    import yaml   # deliberately not wrapped: a run whose config cannot be
                  # written is not a reproducible run, and should fail loudly
    (out / "config.yaml").write_text(yaml.safe_dump(plain, sort_keys=False))

    h = hashlib.sha256((out / "burnin_measurements.csv").read_bytes()).hexdigest()[:16]
    print(f"lots={cfg.n_lots} parts={len(gt)} rows={len(meas)} AF={gen.af:.2f} "
          f"field_years@168h={gen.field_years[gen.t_end]:.3f}")
    print(gt["defect_type"].value_counts().to_string())
    print(f"measurements sha256[:16]={h}")


if __name__ == "__main__":
    main()
